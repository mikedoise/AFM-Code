import Foundation

@main struct EnvironmentTests {
    @MainActor static func main() async throws {
        let root = URL(fileURLWithPath: CommandLine.arguments[1])
        precondition(FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask).first!.path.hasPrefix(root.deletingLastPathComponent().path), "Fixture cache escaped temporary HOME")
        let project = Project()
        let approvals = ToolApprovalService(project: project)
        let context = ToolContext(session: ChatSession(), workspace: Workspace(folderURL: root), approvals: approvals)
        let tool = EnvironmentCheckTool(context: context)
        let path = ShellEnvironment.augmentedPath("/custom/bin:/usr/bin:/bin", developerBin: "/developer/bin")
        precondition(path.hasPrefix("/custom/bin:/usr/bin:/bin:/developer/bin:"))
        precondition(path.contains("/opt/homebrew/bin") && path.contains("/usr/local/bin"))
        precondition(path.components(separatedBy: ":").filter { $0 == "/usr/bin" }.count == 1)
        print("PASS PATH fallback preserves order and adds conventional tool paths")
        let fake = root.appendingPathComponent("gh")
        let sentinel = root.appendingPathComponent("executed")
        try "#!/bin/sh\nprintf ran > '\(sentinel.path)'\nprintf 'gh version 1.2.3\\nSECRET_TOKEN=do-not-report\\n'\n".write(to: fake, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: fake.path)
        let candidates = EnvironmentDiagnostics.candidates(names: ["gh"], environment: ["PATH":""], root: root)
        precondition(candidates.first?.executable == fake)
        precondition(!FileManager.default.fileExists(atPath: sentinel.path))
        precondition(EnvironmentDiagnostics.find("not_allowed", path: root.path, root: root) == nil)
        precondition(EnvironmentDiagnostics.inventory(candidates).contains("execution not tested"))
        try FileManager.default.setAttributes([.posixPermissions: 0o644], ofItemAtPath: fake.path)
        let restricted = EnvironmentDiagnostics.candidates(names: ["gh"], environment: ["PATH": root.path], root: root)
        precondition(restricted.first!.accessRestricted && EnvironmentDiagnostics.inventory(restricted).contains("denied access"))
        print("PASS inventory distinguishes not found from access/execute restriction without executing programs")
        let good = EnvironmentDiagnostics.probeResult(name: "gh", exitCode: 0, output: "gh version 1.2.3\nSECRET_TOKEN=hidden", timedOut: false)
        precondition(good.contains("1.2.3") && !good.contains("SECRET_TOKEN") && !good.contains("hidden"))
        let bad = EnvironmentDiagnostics.probeResult(name: "python3", exitCode: 1, output: "Permission denied; PASSWORD=hidden", timedOut: false)
        precondition(bad.contains("denied access") && !bad.contains("PASSWORD") && !bad.contains("hidden"))
        precondition(EnvironmentDiagnostics.success(name: "gh", output: "gh version SECRET") == nil)
        precondition(EnvironmentDiagnostics.success(name: "gh", output: "gh version 1.2secret") == nil)
        precondition(EnvironmentDiagnostics.success(name: "shell", output: "AFM_SHELL_OK\nSECRET") == nil)
        precondition(EnvironmentDiagnostics.probeResult(name: "gh", exitCode: 0, output: "gh version 1.2.3", timedOut: true).contains("timed out"))
        print("PASS numeric-only success and fixed error classification never relay raw probe output")
        let invalid = try await tool.call(arguments: .init(tool: "gh; touch oops", verifyExecution: true))
        precondition(invalid.contains("Nothing was executed"))
        let unnamed = try await tool.call(arguments: .init(tool: nil, verifyExecution: true))
        precondition(unnamed.contains("Name one tool"))
        let startup = URL(fileURLWithPath: ProcessInfo.processInfo.environment["ZDOTDIR"]!).appendingPathComponent(".zshenv")
        let startupSentinel = root.appendingPathComponent("startup-ran")
        try "printf startup > \(EnvironmentDiagnostics.quote(startupSentinel.path))\n".write(to: startup, atomically: true, encoding: .utf8)
        let inventory = try await tool.call(arguments: .init(tool: nil, verifyExecution: false))
        precondition(inventory.contains("execution not tested") && !inventory.contains("HOME="))
        precondition(approvals.pendingStepIDs.isEmpty)
        precondition(!FileManager.default.fileExists(atPath: startupSentinel.path))
        precondition(inventory.contains("No shell startup capture was run"))
        let readOnly = try await context.runReadOnlyCommand(command: "printf read_only", timeout: 5)
        precondition(readOnly.exitCode == 0 && readOnly.output == "read_only")
        _ = try await context.search(pattern: "fixture")
        precondition(!FileManager.default.fileExists(atPath: startupSentinel.path), "Read-only helper executed startup code")
        print("PASS inventory and built-in read-only helpers do not execute shell startup files")
        func probe(_ name: String, decision: ApprovalDecision) async throws -> String {
            let task = Task { try await tool.call(arguments: .init(tool: name, verifyExecution: true)) }
            for _ in 0..<1000 {
                if let id = approvals.pendingStepIDs.first { approvals.decide(id, decision); return try await task.value }
                try await Task.sleep(for: .milliseconds(5))
            }
            task.cancel(); preconditionFailure("Probe did not request approval")
        }
        let denied = try await probe("shell", decision: .deny)
        precondition(denied.lowercased().contains("declined"))
        precondition(!FileManager.default.fileExists(atPath: startupSentinel.path), "Denied probe executed startup code")
        let passed = try await probe("shell", decision: .approve)
        precondition(passed.contains("shell probe passed"))
        precondition(FileManager.default.fileExists(atPath: startupSentinel.path), "Positive control did not execute startup file after approval")
        try FileManager.default.removeItem(at: startupSentinel)
        let pending = Task { try await tool.call(arguments: .init(tool: "shell", verifyExecution: true)) }
        for _ in 0..<1000 { if !approvals.pendingStepIDs.isEmpty { break }; try await Task.sleep(for: .milliseconds(5)) }
        pending.cancel()
        do { _ = try await pending.value; preconditionFailure("Cancellation swallowed") } catch is CancellationError {}
        precondition(approvals.pendingStepIDs.isEmpty)
        precondition(!FileManager.default.fileExists(atPath: startupSentinel.path), "Cancelled probe executed startup code")
        print("PASS startup code runs only after probe approval, not on deny/cancel")
        let python = try await probe("python3", decision: .approve)
        precondition(python.contains("python3 ") && python.contains("probe passed"))
        precondition(!context.steps.contains { ($0.detail ?? "").contains("SECRET_TOKEN") })
        print("PASS isolated Python interpreter probe and sanitized activity detail")
        let env = ShellEnvironment.augmented(["PATH":"/usr/bin:/bin", "UV_CACHE_DIR":"/explicit/uv", "PIP_CACHE_DIR":"/explicit/pip", "npm_config_cache":"/explicit/npm"])
        precondition(env["UV_CACHE_DIR"] == "/explicit/uv" && env["PIP_CACHE_DIR"] == "/explicit/pip" && env["npm_config_cache"] == "/explicit/npm")
        let cache = ShellEnvironment.toolCacheDir()!
        precondition(cache.hasPrefix(root.deletingLastPathComponent().path))
        try "export AFM_FIXTURE_CACHED_VALUE=fixture\n".write(to: startup, atomically: true, encoding: .utf8)
        let future = Date().addingTimeInterval(700)
        let fresh = await ShellEnvironment.resolved(now: future)
        precondition(fresh?["AFM_FIXTURE_CACHED_VALUE"] == "fixture")
        precondition(ShellEnvironment.inspectionSnapshot().summary.contains("Previously captured"))
        try "exit 3\n".write(to: startup, atomically: true, encoding: .utf8)
        let stale = await ShellEnvironment.resolved(now: future.addingTimeInterval(700))
        precondition(stale?["AFM_FIXTURE_CACHED_VALUE"] == "fixture")
        precondition(ShellEnvironment.captureSummary.contains("previous exported"))
        print("PASS explicit cache overrides, fixture-contained cache API and stale export fallback after failed refresh")
    }
}
